#!/usr/bin/env python3
"""Write tokens.css (screens: light and dark, and the few components every
rta-style page shares) and document.css (print) from tokens.json. Run after editing the JSON;
tests/test_rta_style.py fails when the two disagree."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def css(tokens):
    def block(palette):
        return ";".join(f"--{k}:{v}" for k, v in palette.items())
    f = tokens["font"]
    return f"""/* Generated by .claude/skills/rta-style/build.py from tokens.json. Do not edit by hand. */
:root{{color-scheme:light dark;{block(tokens['light'])};--radius:{tokens['radius']};--shadow:{tokens['shadow']};--font:{f['family']}}}
@media (prefers-color-scheme:dark){{:root:not([data-theme=light]){{{block(tokens['dark'])};--shadow:none;color-scheme:dark}}}}
:root[data-theme=dark]{{{block(tokens['dark'])};--shadow:none;color-scheme:dark}}
:root[data-theme=light]{{color-scheme:light}}
*{{box-sizing:border-box}}
html,body{{margin:0;padding:0;background:var(--bg);color:var(--text);font-family:var(--font);font-size:{f['size_base']};line-height:{f['line_height']}}}
h1,h2,h3{{margin:0;font-weight:{f['weight_heading']};letter-spacing:-.01em}}
h1{{font-size:1.5rem}}h2{{font-size:1.1rem;margin:1.6rem 0 .5rem;padding-inline-start:.6rem;border-inline-start:4px solid var(--brand)}}h3{{font-size:.95rem}}
.page{{max-width:1400px;margin:0 auto;padding-left:max(16px,env(safe-area-inset-left,0px));padding-right:max(16px,env(safe-area-inset-right,0px));padding-block-end:2rem}}
.brandbar{{background:var(--bar);color:var(--on-brand);border-bottom:4px solid var(--bar-edge)}}
.brandbar .page{{padding-block:.9rem 1rem}}.brandbar h1{{color:var(--on-brand)}}
.org{{font-size:.8rem;text-transform:uppercase;letter-spacing:.08em;font-weight:600;opacity:.88;margin:0}}
.period{{opacity:.9;margin:.25rem 0 0}}
.grid{{display:grid;gap:.85rem;grid-template-columns:repeat(auto-fit,minmax(min(100%,22rem),1fr))}}
.card,.tile{{background:var(--surface);border:1px solid var(--border);border-radius:var(--radius);padding:.85rem .95rem;box-shadow:var(--shadow);min-width:0}}
.tile{{border-inline-start:5px solid var(--accent)}}.tile--brand{{border-inline-start-color:var(--brand)}}
.tile-label{{font-size:.78rem;color:var(--muted);text-transform:uppercase;letter-spacing:.05em}}
.tile-value{{font-size:2rem;font-weight:700;line-height:1.1;font-variant-numeric:tabular-nums}}
.muted{{color:var(--muted)}}
code{{font-size:.85em;background:var(--surface-2);border-radius:4px;padding:0 .25em}}
table{{border-collapse:collapse}}th{{text-align:start}}
.pill{{display:inline-block;font-size:.72rem;font-weight:700;padding:.12rem .55rem;border-radius:999px;color:var(--on-status)}}
.pill--good{{background:var(--status-good)}}.pill--warn{{background:var(--status-warn)}}.pill--bad{{background:var(--status-bad)}}
a{{color:var(--accent)}}a:focus-visible,button:focus-visible,summary:focus-visible{{outline:2px solid var(--brand);outline-offset:2px}}
@media print{{.brandbar{{-webkit-print-color-adjust:exact;print-color-adjust:exact}}.card,.tile{{break-inside:avoid;box-shadow:none}}}}
"""


def document_css(tokens):
    """The print variant, for reports made from HTML (pandoc and Chromium, for
    example): variables and element rules only. The page that uses it brings
    its own @font-face for 'Doc Sans' (Dubai where licensed and installed, a
    substitute otherwise)."""
    d = tokens["document"]
    block = ";".join(f"--doc-{k}:{v}" for k, v in d.items())
    return f"""/* Generated by .claude/skills/rta-style/build.py from tokens.json. Do not edit by hand. */
:root{{{block};--doc-font:{tokens['document_font']}}}
html{{font-family:var(--doc-font);color:var(--doc-text);background:var(--doc-page)}}
h1,h2,h3,h4{{font-family:var(--doc-font);color:var(--doc-primary);font-weight:700}}
h2{{border-top-color:var(--doc-primary)}}
th{{color:var(--doc-primary);border-bottom-color:var(--doc-primary)}}
a{{color:var(--doc-primary-2)}}
.band{{background:var(--doc-primary);color:var(--doc-on-primary);border-bottom:2mm solid var(--doc-accent);-webkit-print-color-adjust:exact;print-color-adjust:exact}}
.band *{{color:inherit}}
.callout{{background:var(--doc-primary-tint);border-inline-start:1.2mm solid var(--doc-primary);padding:3mm 4mm}}
.callout--key{{background:var(--doc-accent-tint);border-inline-start-color:var(--doc-accent)}}
"""


def main():
    tokens = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
    (HERE / "tokens.css").write_text(css(tokens), encoding="utf-8")
    (HERE / "document.css").write_text(document_css(tokens), encoding="utf-8")
    print("wrote", HERE / "tokens.css", "and", HERE / "document.css")


if __name__ == "__main__":
    main()
